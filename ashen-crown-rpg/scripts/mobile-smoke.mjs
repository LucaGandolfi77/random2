import { chromium } from 'playwright-core';
const appearance={seed:11,skin:'#c69b79',hair:'#3a2820',hairStyle:2,eyes:'#6f8a6a',marking:'none',accent:'#b08b51',outfit:'#2f2b2a'};
const draft={name:'Aren Voss',ancestry:'erdan',classId:'warrior',background:'soldier',attributes:{str:15,dex:12,con:14,int:8,wis:10,cha:13},appearance,difficulty:'balanced'};
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROME_PATH ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',args:['--no-sandbox']});
const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:2});
const page=await context.newPage();
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
await page.goto(process.env.ASHEN_URL ?? 'http://localhost:5173',{waitUntil:'networkidle'});
await page.waitForTimeout(500);
await page.screenshot({path:'smoke/40-mobile-menu.png'});
await page.getByRole('button',{name:/New Chronicle/i}).click();
await page.waitForTimeout(700);
await page.screenshot({path:'smoke/41-mobile-creation.png'});
await page.evaluate(v=>{window.__ASHEN_STORE__.getState().newGame(v);window.__ASHEN_STORE__.getState().skipIntro();},draft);
await page.waitForSelector('.game-screen');
await page.waitForTimeout(2200);
await page.screenshot({path:'smoke/42-mobile-game.png'});
console.log('joystick visible', await page.locator('.joystick').isVisible());
await page.evaluate(()=>window.__ASHEN_STORE__.getState().openDialogue('kaelen_bastion'));
await page.waitForTimeout(500);
await page.screenshot({path:'smoke/43-mobile-dialogue.png'});
await page.evaluate(()=>window.__ASHEN_STORE__.getState().closeDialogue());
await page.evaluate(()=>window.__ASHEN_STORE__.getState().openModal('journal'));
await page.waitForTimeout(500);
await page.screenshot({path:'smoke/44-mobile-journal.png'});
await page.evaluate(()=>window.__ASHEN_STORE__.getState().closeModal());
await page.waitForTimeout(200);
await page.evaluate(()=>window.__ASHEN_STORE__.getState().startCombat('enc_bastion_raiders'));
await page.waitForSelector('.combat-toolbar');
await page.waitForTimeout(1800);
await page.screenshot({path:'smoke/45-mobile-combat.png'});
console.log('errors', errors);

await page.evaluate(() => {
  const store = window.__ASHEN_STORE__;
  const combat = store.getState().combat;
  store.setState({ combat: { ...combat, units: combat.units.map((unit) => unit.side === 'enemy' ? { ...unit, hp: 0, downed: true } : unit) } });
  store.getState().combatEndTurn();
});
await page.waitForSelector('.combat-result', { timeout: 10000 });
await page.waitForTimeout(600);
await page.screenshot({ path: 'smoke/46-mobile-victory.png' });
await page.evaluate(() => window.__ASHEN_STORE__.getState().setEnding('unwritten'));
await page.waitForTimeout(900);
await page.screenshot({ path: 'smoke/47-mobile-ending.png', fullPage: false });
console.log('mobile victory and ending captured');
await browser.close();
