#!/usr/bin/env node
/* Generate 100 solver-approved Arrow Foundry levels. */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { FACTORIES, LEVELS_PER_FACTORY } from "../src/config.js";
import { makeCandidate } from "../src/levels.js";
import { solveLevel } from "../src/solver.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const data = [];

for (let factory = 0; factory < FACTORIES.length; factory++) {
  for (let stage = 0; stage < LEVELS_PER_FACTORY; stage++) {
    const base = 6133 + factory * 1009 + stage * 7919;
    let chosen = null;
    for (let attempt = 0; attempt < 240 && !chosen; attempt++) {
      const seed = (base + attempt * 1013) >>> 0;
      const candidate = makeCandidate(factory, stage, seed);
      if (!candidate) continue;
      if (candidate.doorCount > 0 && candidate.doors.length === 0) continue;
      const result = solveLevel(candidate, { maxNodes: 500000, maxMoves: 180 });
      if (!result.ok) continue;
      const minimum = candidate.arrows.length + candidate.arrows.filter((arrow) => arrow.heavy).length;
      if (result.solution.length < minimum) continue;
      chosen = { ...candidate, par: result.solution.length, solution: result.solution, solverNodes: result.nodes };
    }
    if (!chosen) throw new Error(`No approved level for ${FACTORIES[factory].id}-${stage + 1}`);
    data.push(chosen);
    console.error(`approved ${chosen.id}: arrows=${chosen.arrows.length} moves=${chosen.par} doors=${chosen.doors.length} nodes=${chosen.solverNodes}`);
  }
}

const rows = data.map((level) => `  ${JSON.stringify(level)},`).join("\n");
const body = `// Generated by scripts/validate-levels.mjs. Do not edit by hand.\nexport const LEVEL_DATA = [\n${rows}\n];\n`;
writeFileSync(resolve(root, "src/level-data.js"), body);
console.error(`wrote level-data.js · ${data.length} levels`);
