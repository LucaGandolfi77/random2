export function fmtNumber(value: number, lang: Lang, digits = 0): string {
  return new Intl.NumberFormat(lang === "it" ? "it-IT" : "en-GB", {
    minimumFractionDigits: 0,
    maximumFractionDigits: digits
  }).format(value);
}

export function fmtSigned(value: number, lang: Lang, digits = 0): string {
  const rounded = Math.round(value * 10 ** digits) / 10 ** digits;
  const sign = rounded > 0 ? "+" : rounded < 0 ? "−" : "±";
  return `${sign}${fmtNumber(Math.abs(rounded), lang, digits)}`;
}

export function fmtPercent(value: number, lang: Lang, digits = 1): string {
  return `${fmtNumber(value, lang, digits)}%`;
}

export function fmtEuro(value: number, lang: Lang): string {
  return new Intl.NumberFormat(lang === "it" ? "it-IT" : "en-GB", {
    style: "currency",
    currency: "EUR",
    maximumFractionDigits: 0
  }).format(value);
}

export function fmtCompact(value: number, lang: Lang): string {
  return new Intl.NumberFormat(lang === "it" ? "it-IT" : "en-GB", {
    notation: "compact",
    maximumFractionDigits: 1
  }).format(value);
}
