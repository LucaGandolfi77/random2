#!/usr/bin/env node
/* Generate solver-approved deterministic seeds for all 100 Umbra Sort levels. */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { AREAS, LEVELS_PER_AREA } from "../src/config.js";
import { makeCandidate, validateLevel } from "../src/levels.js";
import { solveLevel } from "../src/solver.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const table = [];
let totalNodes = 0;

for (let area = 0; area < AREAS.length; area++) {
  const row = [];
  for (let stage = 0; stage < LEVELS_PER_AREA; stage++) {
    const base = 8173 + area * 1009 + stage * 7919;
    let approved = null;
    for (let attempt = 0; attempt < 100; attempt++) {
      const simplify = attempt < 16 ? 0 : Math.floor((attempt - 16) / 4);
      const seed = (base + attempt * 1013) >>> 0;
      const candidate = makeCandidate(area, stage, seed, simplify);
      if (!candidate || validateLevel(candidate).length) continue;
      const result = solveLevel(candidate, { maxNodes: 80000, maxDepth: 320, repositionLimit: 24 });
      totalNodes += result.nodes || 0;
      if (result.ok) {
        approved = [seed, simplify];
        break;
      }
    }
    if (!approved) throw new Error(`No solver-approved candidate for ${AREAS[area].id}-${stage + 1}`);
    row.push(approved);
    console.error(`approved ${AREAS[area].id}-${stage + 1}: seed=${approved[0]} simplify=${approved[1]}`);
  }
  table.push(row);
}

const rows = table.map((row) => `  [${row.map(([seed, simplify]) => `[${seed}, ${simplify}]`).join(", ")}]`).join(",\n");
const body = `// Approved [seed, simplify] pairs, generated by scripts/validate-levels.mjs.\nexport const LEVEL_SEEDS = [\n${rows}\n];\n`;
writeFileSync(resolve(root, "src/level-seeds.js"), body);
console.error(`wrote level-seeds.js · solver nodes ${totalNodes}`);
