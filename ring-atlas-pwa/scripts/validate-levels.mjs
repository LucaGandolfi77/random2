#!/usr/bin/env node
/* Generate 100 solver-approved Ring Atlas levels. */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { ATLASES, LEVELS_PER_ATLAS } from "../src/config.js";
import { makeCandidate } from "../src/levels.js";
import { applyMove } from "../src/rules.js";
import { solveLevel } from "../src/solver.js";
const root=resolve(dirname(fileURLToPath(import.meta.url)),".."),data=[];
function advance(offsets,level,moves){let state=offsets.slice();for(const move of moves)state=applyMove(state,level,move);return state;}
for(let atlas=0;atlas<ATLASES.length;atlas++)for(let stage=0;stage<LEVELS_PER_ATLAS;stage++){
  const base=7193+atlas*1009+stage*7919,minMoves=3+atlas+Math.floor(stage/4);let chosen=null;
  for(let attempt=0;attempt<160&&!chosen;attempt++){
    const seed=(base+attempt*1013)>>>0,candidate=makeCandidate(atlas,stage,seed);
    const result=solveLevel(candidate,{maxNodes:300000,maxMoves:120});if(!result.ok||result.solution.length<minMoves)continue;
    const split=Math.min(3,Math.max(1,Math.floor(result.solution.length/4)));
    chosen={...candidate,par:result.solution.length,solution:result.solution,shuffleOffsets:advance(candidate.offsets,candidate,result.solution.slice(0,split)),shuffleSolution:result.solution.slice(split),solverNodes:result.nodes};
  }
  if(!chosen)throw new Error(`No approved level for ${ATLASES[atlas].id}-${stage+1}`);
  data.push(chosen);console.error(`approved ${chosen.id}: rings=${chosen.rings} moves=${chosen.par} nodes=${chosen.solverNodes}`);
}
const rows=data.map(l=>`  ${JSON.stringify(l)},`).join("\n");
writeFileSync(resolve(root,"src/level-data.js"),`// Generated by scripts/validate-levels.mjs. Do not edit by hand.\nexport const LEVEL_DATA = [\n${rows}\n];\n`);
console.error(`wrote level-data.js · ${data.length} levels`);
