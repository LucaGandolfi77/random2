#!/usr/bin/env node
/* Generate 100 solver-approved Vial Garden levels. */
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { GARDENS, LEVELS_PER_GARDEN } from "../src/config.js";
import { makeCandidate } from "../src/levels.js";
import { applyPour, stateMetrics } from "../src/rules.js";
import { solveLevel } from "../src/solver.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const data = [];

function advance(tubes, moves) {
  let state = tubes.map((tube) => tube.slice());
  for (const move of moves) {
    state = applyPour(state, move.from, move.to);
    if (!state) throw new Error("Invalid generated solution");
  }
  return state;
}

for (let garden = 0; garden < GARDENS.length; garden++) {
  for (let stage = 0; stage < LEVELS_PER_GARDEN; stage++) {
    const base = 5179 + garden * 1009 + stage * 7919;
    const minMoves = Math.min(22, 7 + garden * 2 + Math.floor(stage / 3));
    let chosen = null;
    for (let attempt = 0; attempt < 600 && !chosen; attempt++) {
      const seed = (base + attempt * 1013) >>> 0;
      const candidate = makeCandidate(garden, stage, seed);
      const result = solveLevel(candidate, { maxNodes: 250000, maxMoves: 180 });
      if (!result.ok || result.solution.length < minMoves) continue;
      const metrics = stateMetrics(candidate.tubes);
      if (metrics.mixed < candidate.colors - 1) continue;
      const split = Math.min(4, Math.max(1, Math.floor(result.solution.length / 4)));
      chosen = {
        ...candidate,
        par: result.solution.length,
        solution: result.solution,
        shuffleTubes: advance(candidate.tubes, result.solution.slice(0, split)),
        shuffleSolution: result.solution.slice(split)
      };
    }
    if (!chosen) throw new Error(`No approved level for ${GARDENS[garden].id}-${stage + 1}`);
    data.push(chosen);
    console.error(`approved ${chosen.id}: moves=${chosen.par} seed=${chosen.seed}`);
  }
}

const rows = data.map((level) => `  ${JSON.stringify(level)},`).join("\n");
const body = `// Generated by scripts/validate-levels.mjs. Do not edit by hand.\nexport const LEVEL_DATA = [\n${rows}\n];\n`;
writeFileSync(resolve(root, "src/level-data.js"), body);
console.error(`wrote level-data.js · ${data.length} levels`);
