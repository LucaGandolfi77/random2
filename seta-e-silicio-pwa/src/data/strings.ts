export const STRINGS: Record<Lang, Record<Key, string>> = { it: IT, en: EN };
export type StringKey = Key;

export function t(lang: Lang, key: StringKey): string {
  return STRINGS[lang][key];
}

export function interpolate(text: string, values: Record<string, string | number>): string {
  return text.replace(/\{(\w+)\}/g, (_, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : `{${key}}`
  );
}

export function fmtNumber(value: number, lang: Lang): string {
  return new Intl.NumberFormat(lang === "it" ? "it-IT" : "en-GB").format(value);
}
