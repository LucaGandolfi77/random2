export function blockLabel(name) {
  const key = normalize(name);
  if (!key) return '—';
  return key.split('_').map(part => part ? part[0].toUpperCase() + part.slice(1) : '').join(' ');
}

export function blockCategory(name) {
  const key = normalize(name);
  if (isGlassBlock(key) || key === 'glass') return 'vetri';
  if (['water', 'ice', 'packed_ice', 'blue_ice'].includes(key)) return 'acqua';
  if (isRoofBlock(key)) return 'tetti';
  if (isLeafBlock(key) || isCropBlock(key) || ['grass_block', 'farmland', 'short_grass', 'tall_grass', 'fern', 'moss_block', 'podzol', 'dirt', 'coarse_dirt', 'dirt_path', 'sand', 'clay', 'snow', 'snow_block', 'sunflower', 'dandelion', 'poppy', 'cornflower', 'oxeye_daisy', 'allium', 'lily_of_the_valley', 'red_tulip', 'white_tulip', 'pink_tulip', 'orange_tulip', 'azure_bluet', 'rose_bush', 'peony', 'lilac', 'sweet_berry_bush', 'dead_bush', 'lily_pad', 'hay_block', 'pumpkin'].includes(key)) return 'vegetazione';
  if (isLogBlock(key) || key.includes('planks') || key.endsWith('_door') || key.endsWith('_trapdoor') || key.endsWith('_fence') || key.endsWith('_fence_gate') || ['barrel', 'chest', 'crafting_table', 'scaffolding', 'bookshelf', 'chiseled_bookshelf', 'ladder', 'lever'].includes(key)) return 'legno';
  if (['asphalt', 'gray_concrete_powder', 'white_concrete_powder', 'dirt_path', 'gravel', 'cobblestone', 'red_concrete', 'red_terracotta', 'smooth_stone', 'stone', 'andesite', 'polished_andesite', 'sand', 'clay', 'iron_block'].includes(key)) return 'strade';
  if (['grass_block', 'farmland', 'podzol', 'dirt', 'coarse_dirt', 'moss_block', 'green_terracotta', 'green_wool'].includes(key)) return 'aree';
  if (key.includes('stone') || key.includes('brick') || key.includes('terracotta') || key.includes('concrete') || key.includes('sandstone') || key.includes('deepslate') || key.includes('granite') || key.includes('diorite') || key.includes('andesite') || key.includes('calcite') || key.includes('tuff') || key.includes('mud') || key.includes('quartz')) return 'muri';
  return 'altro';
}

const KNOWN_SUFFIXES = /(_stairs|_slab|_wall|_button|_pressure_plate|_fence_gate|_fence|_sign|_carpet|_banner)$/;
const WOOD_BLOCKS = new Set([
  'oak_planks', 'birch_planks', 'spruce_planks', 'jungle_planks', 'acacia_planks',
  'dark_oak_planks', 'cherry_planks', 'mangrove_planks', 'warped_planks', 'crimson_planks'
]);
const WOOD_NAMES = new Set(['oak', 'birch', 'spruce', 'jungle', 'acacia', 'dark_oak', 'cherry', 'mangrove', 'warped', 'crimson']);

export function isKnownBlock(name) {
  const key = normalize(name);
  if (!key) return false;
  if (BLOCK_COLORS[key]) return true;
  if (KNOWN_SUFFIXES.test(key)) {
    const base = key.replace(KNOWN_SUFFIXES, '').replace(/_wall$/, '');
    if (BLOCK_COLORS[base] || WOOD_BLOCKS.has(base) || STRUCTURE_COLORS[base]) return true;
    if (WOOD_NAMES.has(base)) return true;
    if (base.endsWith('_brick') && (BLOCK_COLORS[`${base}s`] || STRUCTURE_COLORS[`${base}s`])) return true;
    if (BLOCK_COLORS[`${base}s`] || STRUCTURE_COLORS[`${base}s`]) return true;
  }
  if (key === 'glass_pane') return true;
  if (key.endsWith('_glass_pane')) return !!BLOCK_COLORS[key.slice(0, -5)];
  if (key.endsWith('_door') || key.endsWith('_trapdoor')) {
    const base = key.replace(/(_door|_trapdoor)$/, '');
    return base === 'iron' || WOOD_NAMES.has(base) || !!BLOCK_COLORS[base] || WOOD_BLOCKS.has(`${base}_planks`);
  }
  if (key.endsWith('_banner')) {
    const base = key.slice(0, -7).replace(/_wall$/, '');
    if (BLOCK_COLORS[`${base}_concrete`] || BLOCK_COLORS[`${base}_wool`] || BLOCK_COLORS[base]) return true;
  }
  if (key.endsWith('_leaves')) return true;
  if (key.endsWith('_log')) return true;
  if (key.endsWith('_rod') || key.endsWith('_bed')) return true;
  return false;
}

