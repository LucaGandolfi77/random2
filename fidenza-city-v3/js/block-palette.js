export function wallFallbackBlock(building) {
  if (building?.facadeStyle === 'historic' || building?.facadeStyle === 'civic') return 'terracotta';
  if (building?.facadeStyle === 'rural') return 'bricks';
  if (building?.facadeStyle === 'industrial') return 'gray_concrete';
  return 'white_concrete';
}

export function roofFallbackBlock(building) {
  if (building?.roofShape === 'flat' || ['industrial', 'warehouse', 'factory', 'commercial', 'garage', 'train_station', 'school', 'hospital', 'sport'].includes(building?.kind)) {
    return 'gray_concrete';
  }
  return 'granite_stairs';
}

export const DETAIL_SIZE = 1; // dettagli voxel da 1 metro

export function detailPaletteFor(building, blocks = {}) {
  const info = building?.arnis || {};
  const wall = blocks.wallLower || blocks.wall || info.wallLower || info.wall || wallFallbackBlock(building);
  const roof = blocks.roof || info.roof || roofFallbackBlock(building);
  const family = blockKey(wall);
  let accent = 'stone_bricks';
  if (family.includes('terracotta') || family.includes('brick') || family.includes('mud')) accent = 'stone_bricks';
  else if (family.includes('sandstone')) accent = 'smooth_sandstone';
  else if (family.includes('concrete') || family.includes('quartz') || family.includes('calcite')) accent = 'light_gray_concrete';
  else if (family.includes('planks') || family.includes('log')) accent = 'spruce_planks';
  else if (family.includes('stone') || family.includes('andesite') || family.includes('cobblestone') || family.includes('deepslate')) accent = 'stone_bricks';
  const wood = family.includes('planks') || family.includes('log') ? 'spruce_planks' : 'dark_oak_planks';
  return {
    wall,
    roof,
    accent,
    trim: baseBlock(roof),
    wood,
    glass: blocks.glass || info.glass || null,
    door: blocks.door || info.door || null
  };
}

const RED_CYCLEWAY_BLOCKS = new Set(['red_terracotta', 'red_concrete']);

/**
 * Restituisce il blocco del manto stradale.
 * Le scelte esplicite dell'editor (override) hanno sempre la precedenza.
 */
export function roadSurfaceBlock({ kind = '', source = '', override = '', seed = 0 } = {}) {
  const overrideKey = baseBlock(override);
  if (overrideKey) return overrideKey;
  const sourceKey = baseBlock(source);
  if (kind === 'cycleway') {
    return RED_CYCLEWAY_BLOCKS.has(sourceKey) ? sourceKey : 'red_terracotta';
  }
  if (kind === 'pedestrian' || kind === 'footway' || kind === 'steps') {
    return sourceKey || 'gray_concrete';
  }
  if (kind === 'path') return 'dirt_path';
  if (kind === 'track') return 'gravel';
  if (kind === 'service' || kind === 'unclassified' || kind === 'living_street') {
    return 'gravel';
  }
  return 'asphalt';
}

/**
 * Marciapiedi chiari, con una piccola alternanza di pietra.
 */
export function sidewalkBlock({ kind = '', source = '', override = '', seed = 0 } = {}) {
  const overrideKey = baseBlock(override);
  if (overrideKey) return overrideKey;
  const sourceKey = baseBlock(source);
  if (kind === 'pedestrian' || kind === 'footway' || kind === 'steps') {
    return sourceKey || 'gray_concrete';
  }
  return seed % 3 === 0 ? 'smooth_stone' : 'light_gray_concrete';
}

