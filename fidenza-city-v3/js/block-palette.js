export function baseBlock(name) {
  const key = normalize(name);
  if (STAIR_BASE[key]) return STAIR_BASE[key];
  if (SLAB_BASE[key]) return SLAB_BASE[key];
  if (key.endsWith('_stairs')) return key.slice(0, -7);
  if (key.endsWith('_slab')) return key.slice(0, -5);
  return key;
}

export function speciesFromLeaves(name) {
  const key = normalize(name);
  if (!key.endsWith('_leaves')) return 'oak';
  return key.replace(/_leaves$/, '');
}

export function dominant(entries) {
  let best = null;
  let bestCount = -1;
  for (const [name, count] of entries) {
    if (count > bestCount) { best = name; bestCount = count; }
  }
  return best;
}

export function countMap() {
  return new Map();
}

export function bump(map, key, amount = 1) {
  if (!key) return;
  map.set(key, (map.get(key) || 0) + amount);
}
