const normalize = name => String(name || '').replace(/^minecraft:/, '').replace(/\s+/g, '_').toLowerCase();

export function blockKey(name) {
  return normalize(name);
}

function hashString(value) {
  let hash = 0;
  for (const char of String(value)) hash = (hash * 31 + char.charCodeAt(0)) | 0;
  return Math.abs(hash);
}

export function hashColor(name, saturation = 0.42, lightness = 0.52) {
  const hue = (hashString(normalize(name)) % 360) / 360;
  return hslToHex(hue, saturation, lightness);
}

function hslToHex(h, s, l) {
  const a = s * Math.min(l, 1 - l);
  const f = n => {
    const k = (n + h * 12) % 12;
    const color = l - a * Math.max(-1, Math.min(k - 3, Math.min(9 - k, 1)));
    return Math.round(color * 255).toString(16).padStart(2, '0');
  };
  return `#${f(0)}${f(8)}${f(4)}`;
}

