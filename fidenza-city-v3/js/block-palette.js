export function blockColor(name) {
  const key = normalize(name);
  if (BLOCK_COLORS[key]) return BLOCK_COLORS[key];

  // Varianti di forma: stairs, slab, wall, button, pressure plate, fence...
  if (/(_stairs|_slab|_wall|_button|_pressure_plate|_fence_gate|_fence|_sign)$/.test(key)) {
    const base = key.replace(/(_stairs|_slab|_wall|_button|_pressure_plate|_fence_gate|_fence|_sign)$/, '').replace(/_wall$/, '');
    if (WOOD_SPECIES[base]) return blockColor(WOOD_SPECIES[base]);
    if (BLOCK_COLORS[base]) return BLOCK_COLORS[base];
    if (STRUCTURE_COLORS[base]) return STRUCTURE_COLORS[base];
    if (base.endsWith('_brick')) {
      const material = base.slice(0, -6);
      if (STRUCTURE_COLORS[`${material}_brick`]) return STRUCTURE_COLORS[`${material}_brick`];
    }
    const plural = `${base}s`;
    if (BLOCK_COLORS[plural]) return BLOCK_COLORS[plural];
    if (STRUCTURE_COLORS[plural]) return STRUCTURE_COLORS[plural];
  }

  if (/(_door|_trapdoor)$/.test(key)) {
    const base = key.replace(/(_door|_trapdoor)$/, '');
    if (base === 'iron') return '#b8b8b8';
    if (BLOCK_COLORS[base]) return BLOCK_COLORS[base];
    if (WOOD_SPECIES[base]) return blockColor(WOOD_SPECIES[base]);
  }

  if (key === 'glass_pane') return BLOCK_COLORS.glass;
  if (key.endsWith('_glass_pane')) {
    return blockColor(key.slice(0, -5));
  }

  if (key.endsWith('_carpet')) {
    const base = key.slice(0, -7);
    if (WOOD_SPECIES[base]) return blockColor(WOOD_SPECIES[base]);
    if (BLOCK_COLORS[`${base}_wool`]) return BLOCK_COLORS[`${base}_wool`];
    if (BLOCK_COLORS[`${base}_concrete`]) return BLOCK_COLORS[`${base}_concrete`];
  }

  if (key.endsWith('_banner')) {
    const base = key.slice(0, -7).replace(/_wall$/, '');
    if (BLOCK_COLORS[`${base}_concrete`]) return BLOCK_COLORS[`${base}_concrete`];
    if (BLOCK_COLORS[`${base}_wool`]) return BLOCK_COLORS[`${base}_wool`];
  }

  if (key.endsWith('_leaves')) {
    if (BLOCK_COLORS[key]) return BLOCK_COLORS[key];
    if (key.includes('cherry')) return BLOCK_COLORS.cherry_leaves;
    return '#4f7a3a';
  }

  if (key.endsWith('_log')) {
    if (BLOCK_COLORS[key]) return BLOCK_COLORS[key];
    return '#5b472a';
  }

  // Blocchi decorativi non mappati: meglio un grigio neutro che un colore
  // casuale che rovinerebbe la mappa.
  if (/(flower|tulip|bluet|daisy|poppy|dandelion|orchid|allium|lilac|peony|rose|sunflower|cornflower|lily)/.test(key)) {
    return hashColor(key, 0.45, 0.6);
  }
  return '#8a8a86';
}


