import {createWorld} from '../src/world.js';
import assert from 'node:assert/strict';
const w=createWorld();
assert.equal(w.player.ammoStock.harpoon,5);
w.player.x=1000;w.player.y=1000;
assert.equal(w.buyAmmo('chain'),false,'ammo only available at a port');
w.player.x=480;w.player.y=650;
assert.equal(w.buyAmmo('flame',2),true);
assert.equal(w.player.ammoStock.flame,10);
assert.equal(w.useAbility(),true);
assert.equal(w.useAbility(),false,'ability has cooldown');
w.player.hull=30;
w.player.abilityCool=0;
assert.equal(w.useAbility(),true);
assert.equal(w.player.hull,58);
assert.equal(w.issueBounty(),true);
assert.equal(w.issueBounty(),false,'one active bounty at a time');
const monster=w.monsters[0];
w.player.x=monster.x-30;w.player.y=monster.y;w.player.angle=0;w.player.ammo='harpoon';w.player.ammoStock.harpoon=2;w.player.cool=0;w.player.target=monster;
w.fire(w.player,monster,400,'harpoon');
w.update(.01,{steer:0,throttle:0,fire:false,collect:false});
assert.equal(monster.active,false,'harpoon fire can defeat a sea monster');
const merchant=w.npcs.find(n=>n.role==='merchant');
w.player.x=merchant.x-65;w.player.y=merchant.y;w.player.angle=0;w.player.target=merchant;w.player.ammo='round';w.player.cool=0;merchant.hull=10;
w.update(.01,{steer:0,throttle:0,fire:true,collect:false});
for(let i=0;i<10&&merchant.hull===10;i++)w.update(.05,{steer:0,throttle:0,fire:true,collect:false});
assert.equal(w.player.outlaw,true,'attacking a merchant marks the captain outlaw');
const wreckWorld=createWorld(),wreck=wreckWorld.wrecks[0];wreckWorld.player.x=wreck.x;wreckWorld.player.y=wreck.y;assert.equal(wreckWorld.recoverWreck(),true);assert.equal(wreck.recovered,true);assert.equal(wreckWorld.recoverWreck(),false,'wrecks cannot be salvaged twice');const landmark=wreckWorld.landmarks[0];assert.equal(wreckWorld.discover(landmark),true);assert.equal(wreckWorld.discover(landmark),false,'discovery rewards are one-time');assert.equal(wreckWorld.regionAt({x:3000,y:2100}).id,'maw');assert.equal(wreckWorld.regionAt({x:300,y:300}).id,'cinder');console.log('special ammunition, ability, bounty, monster and exploration tests passed');
