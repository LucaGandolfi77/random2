import {createWorld} from '../src/world.js';
import assert from 'node:assert/strict';
const game=createWorld();
assert.equal(game.currentMission().id,'first-wake');
assert.equal(game.buy('salt'),true);
assert.equal(game.player.cargo.salt,3);
assert.equal(game.player.coins,84);
assert.equal(game.player.coins+=100,184);
assert.equal(game.player.cargo.salt,3);
assert.equal(game.repair(),true);
game.player.coins=100;
assert.equal(game.upgrade(),false,'upgrade should fail without enough currency');
game.player.coins=500;
assert.equal(game.upgrade(),true);
assert.equal(game.player.cannonLevel,2);
const before=game.player.xp;
game.player.x=1350;game.player.y=480;
assert.equal(game.deliverContract(),true);
assert.equal(game.player.xp,before+80);
assert.equal(game.currentMission().id,'whispered-name');
assert.equal(game.missions[0].status,'complete');
console.log('world economy and campaign tests passed');
