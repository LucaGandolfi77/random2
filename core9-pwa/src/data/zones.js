export const ZONES = BASE_ZONES.concat(SPECIAL_ZONES);
export const BASE_ZONE_IDS = BASE_ZONES.map((z) => z.id);
export const SPECIAL_ZONE_IDS = SPECIAL_ZONES.map((z) => z.id);
export const ZONE_BY_ID = Object.fromEntries(ZONES.map((z) => [z.id, z]));

export function stageForLevel(level) {
  if (!level || level < 1) return 0;
  let stage = 0;
  for (let i = 0; i < STAGE_LEVELS.length; i++) {
    if (level >= STAGE_LEVELS[i]) stage = i + 1;
  }
  return stage;
}

export function siteZones(siteDef) {
  return siteDef.zoneIds.map((id) => {
    const base = ZONE_BY_ID[id];
    const plot = siteDef.plots[id] || base.plot;
    return { ...base, plot, palette: siteDef.palette || base.palette };
  });
}

