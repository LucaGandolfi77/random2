/*
 * tools/sitemap.mjs — regenerate sitemap.xml from the repository.
 *
 *   node tools/sitemap.mjs            # write sitemap.xml
 *   node tools/sitemap.mjs --check    # exit 1 if the committed copy is stale
 *
 * The lastmod of a URL is the date of the last commit that touched the
 * files behind it, which is the only definition of "last modified" that is
 * true. Hand-written dates go stale the day they are written; these come
 * from git, so they cannot.
 *
 * Only deployed URLs belong here. A sitemap full of 404s is a negative
 * signal, not a comprehensive one.
 */
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { join, dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const BASE = "https://lucagandolfi77.github.io/random2/";

/* The pages that are not a project folder but are still published. */
const EXTRA = [
  "portfolio/cv.html",
  "portfolio/verify.html",
  "portfolio/now.html",
  "portfolio/audit/report.html",
  "portfolio/notes/index.html",
  "portfolio/notes/corpus.html",
  "portfolio/notes/copy.html",
  "portfolio/notes/audit.html",
];

function git(...args) {
  return execFileSync("git", args, { cwd: root, encoding: "utf8" }).trim();
}

/* The date of the last commit that touched a path, or null. */
function lastmod(path) {
  try {
    return git("log", "-1", "--format=%as", "--", path);
  } catch {
    return "";
  }
}

function urlPath(file) {
  if (file === "index.html") return "";
  return file.replace(/index\.html$/, "");
}

const pages = [];

/* The hub. */
pages.push({ file: "index.html", loc: BASE });

/* One entry per project folder that is committed and has an index.html. */
const dirs = readdirSync(root, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !d.name.startsWith(".") && d.name !== "EADS" && d.name !== "tools" && d.name !== "shared" && d.name !== "pokesurvivor-bot")
  .map((d) => d.name)
  .sort();
for (const dir of dirs) {
  if (!existsSync(join(root, dir, "index.html"))) continue;
  if (!git("ls-files", "--error-unmatch", `${dir}/index.html`)) continue;
  pages.push({ file: `${dir}/index.html`, loc: BASE + dir + "/" });
}

/* The portfolio's own pages. */
for (const file of EXTRA) {
  if (!existsSync(join(root, file))) continue;
  pages.push({ file, loc: BASE + urlPath(file) });
}

const today = new Date().toISOString().slice(0, 10);

const body = pages.map((p) => {
  /* A page that is staged but not committed yet has no git date. Give it
     today's date rather than a placeholder that would go stale on the first
     deploy; once the commit exists, its real date takes over. */
  const date = lastmod(p.file) || lastmod(p.file.replace(/index\.html$/, "")) || today;
  return `  <url>\n    <loc>${p.loc}</loc>\n    <lastmod>${date}</lastmod>\n  </url>`;
}).join("\n");

const xml = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Sitemap for ${BASE}
     Generated by tools/sitemap.mjs — one entry per page that is committed
     and deployed. The lastmod of each is the date of the last commit that
     touched the files behind it, read from git, so it cannot go stale.
     Run: node tools/sitemap.mjs -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${body}
</urlset>
`;

const target = join(root, "sitemap.xml");

if (process.argv.includes("--check")) {
  const stored = readFileSync(target, "utf8");
  if (stored !== xml) {
    console.error("FAIL  sitemap.xml is stale — run: node tools/sitemap.mjs");
    process.exit(1);
  }
  console.log("OK    sitemap.xml is up to date");
  process.exit(0);
}

writeFileSync(target, xml);
console.log(`wrote sitemap.xml (${pages.length} urls)`);
